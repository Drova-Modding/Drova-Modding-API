"""Lists Drova's addressable environment prefabs (path -> asset guid) from the Addressables catalog.

Writes the map editor's prefab catalog, Drova Modding API/Systems/MapEditor/MapPrefabCatalog.g.cs. Rerun after a game update:
    python Python/envPrefabCatalog.py ["<game dir>"]
"""
import base64
import json
import os
import re
import struct
import sys

GAME = sys.argv[1] if len(sys.argv) > 1 else r"C:\Program Files (x86)\Steam\steamapps\common\Drova - Forsaken Kin"
CATALOG = os.path.join(GAME, "Drova_Data", "StreamingAssets", "aa", "catalog.json")
OUT = os.path.join(os.path.dirname(__file__), "..", "Drova Modding API", "Systems", "MapEditor", "MapPrefabCatalog.g.cs")
ROOTS = ("Assets/Objects/Environment/", "Assets/Objects/Prefabs/Environment/")


def read_keys(data):
    count = struct.unpack_from("<i", data, 0)[0]
    return data, count


def key_at(data, offset):
    kind = data[offset]
    offset += 1
    if kind == 0:  # ascii string
        length = struct.unpack_from("<i", data, offset)[0]
        return data[offset + 4:offset + 4 + length].decode("ascii", "replace")
    if kind == 1:  # unicode string
        length = struct.unpack_from("<i", data, offset)[0]
        return data[offset + 4:offset + 4 + length].decode("utf-16-le", "replace")
    return None


def main():
    catalog = json.load(open(CATALOG, encoding="utf-8"))
    ids = catalog["m_InternalIds"]
    keys = base64.b64decode(catalog["m_KeyDataString"])
    buckets = base64.b64decode(catalog["m_BucketDataString"])
    entries = base64.b64decode(catalog["m_EntryDataString"])

    entry_count = struct.unpack_from("<i", entries, 0)[0]
    entry_ids = [struct.unpack_from("<7i", entries, 4 + i * 28)[0] for i in range(entry_count)]

    guid_re = re.compile(r"^[0-9a-f]{32}$")
    by_path = {}
    bucket_count = struct.unpack_from("<i", buckets, 0)[0]
    pos = 4
    for _ in range(bucket_count):
        data_offset, count = struct.unpack_from("<2i", buckets, pos)
        pos += 8
        bucket_entries = struct.unpack_from("<%di" % count, buckets, pos)
        pos += 4 * count
        key = key_at(keys, data_offset)
        if not key or not guid_re.match(key):
            continue
        for entry in bucket_entries:
            path = ids[entry_ids[entry]]
            if path.endswith(".prefab") and path.startswith(ROOTS):
                by_path[path] = key

    rows = sorted(by_path.items())
    lines = [
        "// <auto-generated> by Python/envPrefabCatalog.py from the game's Addressables catalog. Do not edit. </auto-generated>",
        "namespace Drova_Modding_API.Systems.MapEditor",
        "{",
        "    internal static partial class MapPrefabCatalog",
        "    {",
        "        /// <summary>",
        "        /// Every addressable environment prefab: asset path and addressable guid.",
        "        /// </summary>",
        "        internal static readonly (string Path, string Guid)[] Prefabs =",
        "        [",
    ]
    lines += ['            ("%s", "%s"),' % (p, g) for p, g in rows]
    lines += ["        ];", "    }", "}", ""]
    open(OUT, "w", encoding="utf-8", newline="\r\n").write("\n".join(lines))
    print("%d prefabs -> %s" % (len(rows), os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
